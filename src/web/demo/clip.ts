/** Placeholder results for the offline demo: an SVG poster card and, where the browser allows, a short recorded canvas clip. */

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);

export function posterDataUrl(prompt: string, note: string): string {
  const excerpt = esc(prompt.replace(/\s+/g, ' ').slice(0, 230));
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="640" height="360" viewBox="0 0 640 360">
<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#1f2937"/><stop offset="1" stop-color="#312e81"/></linearGradient></defs>
<rect width="640" height="360" fill="url(#g)"/>
<text x="32" y="56" fill="#b6ff3b" font-family="monospace" font-size="18">${esc(note)}</text>
<foreignObject x="32" y="80" width="576" height="240"><div xmlns="http://www.w3.org/1999/xhtml" style="color:#e5e7eb;font:14px/1.5 monospace">${excerpt}…</div></foreignObject>
</svg>`;
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

const SIZES: Record<string, [number, number]> = { '16:9': [640, 360], '9:16': [360, 640], '1:1': [480, 480], '4:3': [640, 480], '3:4': [480, 640], '21:9': [672, 288] };

function wrap(ctx: CanvasRenderingContext2D, text: string, maxWidth: number, maxLines: number): string[] {
  const lines: string[] = [];
  let line = '';
  for (const word of text.split(/\s+/)) {
    const next = line ? `${line} ${word}` : word;
    if (ctx.measureText(next).width > maxWidth && line) {
      lines.push(line);
      line = word;
      if (lines.length === maxLines) break;
    } else line = next;
  }
  if (line && lines.length < maxLines) lines.push(line);
  return lines;
}

const blobToDataUrl = (blob: Blob) =>
  new Promise<string>((resolve, reject) => {
    const r = new FileReader();
    r.onload = () => resolve(String(r.result));
    r.onerror = () => reject(r.error);
    r.readAsDataURL(blob);
  });

/**
 * Records a few seconds of an animated card (shot timeline + prompt excerpt) with MediaRecorder.
 * Resolves undefined when the browser can't record (no MediaRecorder, blocked canvas capture, …).
 */
export async function recordClip(opts: { prompt: string; aspect: string; shotStarts: number[]; durationSec: number; seconds?: number }): Promise<string | undefined> {
  try {
    if (typeof MediaRecorder === 'undefined') return undefined;
    const [w, h] = SIZES[opts.aspect] ?? SIZES['16:9']!;
    const canvas = document.createElement('canvas');
    canvas.width = w;
    canvas.height = h;
    const ctx = canvas.getContext('2d');
    if (!ctx || typeof canvas.captureStream !== 'function') return undefined;
    const mime = ['video/webm;codecs=vp9', 'video/webm;codecs=vp8', 'video/webm'].find((m) => MediaRecorder.isTypeSupported(m));
    if (!mime) return undefined;

    const seconds = opts.seconds ?? 3.2;
    const fps = 24;
    const recorder = new MediaRecorder(canvas.captureStream(fps), { mimeType: mime, videoBitsPerSecond: 900_000 });
    const chunks: Blob[] = [];
    recorder.ondataavailable = (e) => e.data.size > 0 && chunks.push(e.data);
    const finished = new Promise<void>((resolve) => (recorder.onstop = () => resolve()));

    const started = performance.now();
    const draw = () => {
      const t = (performance.now() - started) / 1000;
      const p = Math.min(1, t / seconds);
      const g = ctx.createLinearGradient(0, 0, w, h);
      g.addColorStop(0, '#111827');
      g.addColorStop(1, '#312e81');
      ctx.fillStyle = g;
      ctx.fillRect(0, 0, w, h);
      for (let i = 0; i < 3; i++) {
        const x = w * (0.5 + 0.35 * Math.sin(t * 0.9 + i * 2.1));
        const y = h * (0.5 + 0.3 * Math.cos(t * 0.7 + i * 1.7));
        const r = Math.max(w, h) * 0.38;
        const rg = ctx.createRadialGradient(x, y, 0, x, y, r);
        rg.addColorStop(0, i === 0 ? 'rgba(182,255,59,0.28)' : i === 1 ? 'rgba(99,102,241,0.35)' : 'rgba(56,189,248,0.25)');
        rg.addColorStop(1, 'rgba(0,0,0,0)');
        ctx.fillStyle = rg;
        ctx.fillRect(0, 0, w, h);
      }
      const pad = Math.round(w * 0.05);
      ctx.fillStyle = '#b6ff3b';
      ctx.font = `600 ${Math.round(h * 0.045)}px monospace`;
      ctx.textBaseline = 'top';
      ctx.fillText('DEMO CLIP · not generated by H3', pad, pad);
      ctx.fillStyle = '#e5e7eb';
      ctx.font = `${Math.round(h * 0.04)}px monospace`;
      const lines = wrap(ctx, opts.prompt.replace(/\s+/g, ' '), w - pad * 2, 6);
      lines.forEach((l, i) => ctx.fillText(l, pad, pad + h * 0.12 + i * h * 0.058));
      // shot timeline with a moving playhead
      const y = h - pad * 1.4;
      ctx.fillStyle = 'rgba(255,255,255,0.18)';
      ctx.fillRect(pad, y, w - pad * 2, 6);
      ctx.fillStyle = '#e5e7eb';
      for (const s of opts.shotStarts) ctx.fillRect(pad + (s / 1000 / opts.durationSec) * (w - pad * 2) - 1, y - 5, 3, 16);
      ctx.fillStyle = '#b6ff3b';
      ctx.fillRect(pad, y, p * (w - pad * 2), 6);
    };

    draw();
    recorder.start(250);
    const timer = setInterval(draw, 1000 / fps);
    await new Promise((r) => setTimeout(r, seconds * 1000));
    clearInterval(timer);
    recorder.stop();
    await finished;
    if (chunks.length === 0) return undefined;
    return await blobToDataUrl(new Blob(chunks, { type: 'video/webm' }));
  } catch {
    return undefined;
  }
}
